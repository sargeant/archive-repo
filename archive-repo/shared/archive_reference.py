from types import SimpleNamespace
from collections import namedtuple
import dateutil.parser as dp
import warnings
import json

#########################
## Upgrade definitions ##
#########################

current_magic = "E!vIA5L86J2I"

dead_end_magic = []

UpgradeInstruction = namedtuple("UpgradeInstruction", ["result", "issues", "prs"])

upgrades = {
    "B8n2c@e8kvfx": UpgradeInstruction(
        result="E!vIA5L86J2I",
        issues=None,
        prs="""
            fragment prFields on PullRequest {
                number
                baseRepository { nameWithOwner }
                baseRefName
                baseRefOid
                headRepository { nameWithOwner }
                headRefName
                headRefOid
                mergeCommit { oid }
            }""",
    )
}


def _validate_upgrade_chain():
    "Fail fast at import time if an upgrade step doesn't chain to current_magic."
    for start, instructions in upgrades.items():
        seen = {start}
        result = instructions.result
        while result != current_magic:
            if result not in upgrades:
                raise AssertionError(
                    f"Upgrade chain from magic {start!r} does not reach "
                    f"current_magic {current_magic!r} (stuck at {result!r})"
                )
            if result in seen:
                raise AssertionError(f"Upgrade chain from magic {start!r} cycles")
            seen.add(result)
            result = upgrades[result].result


_validate_upgrade_chain()


def get_current_magic():
    return current_magic


def is_current_magic(magic):
    return magic == current_magic


def is_legacy_magic(magic):
    return magic in upgrades


def is_dead_end_magic(magic):
    return magic in dead_end_magic


def is_valid_magic(magic):
    return is_current_magic(magic) or is_legacy_magic(magic) or is_dead_end_magic(magic)


def get_upgrade_instructions(magic):
    return upgrades[magic]


